/**
 * M8-12b safety: a password hash is in the text of the access migration file (`rawJson`) and in NO `toString` of anything that holds that file: the file itself,
 * its generation result, the wrappers the screens and the runner pass around. One test per class, so a red list names the classes to redact.
 */
class AccessSecretsToStringTest {
    private val hash = "SENTINEL-HASH-tostring-xyz"
    private val text = F.accessFile(vhosts = listOf(F.vhost("/orders")), users = listOf(F.user("svc", hash)), permissions = listOf(F.permission("/orders", "svc")), queues = listOf(F.queue("jobs", type = "quorum", vhost = "/orders")))

    private val generated: GenerationResult.Generated by lazy {
        assertIs<GenerationResult.Generated>(ConversionReviewsRef.core(text).generate(GenerationRequest(emptySet(), "legacy.json")))
    }
    private val accessFile: MigrationFile by lazy { assertNotNull(generated.migrations.firstOrNull { it.access }, "no access file was generated").file }

    private fun clean(what: String, shown: String) = assertFalse(shown.contains(hash) || shown.contains("\"passwordHash\""), "$what prints the hash or the file text: ${shown.take(160)}")

    @Test fun `premise - the access file text holds the hash`() = kotlin.test.assertTrue(accessFile.rawJson.contains(hash))

    @Test fun `MigrationFile`() = clean("MigrationFile.toString", accessFile.toString())
    @Test fun `GeneratedMigration`() = clean("GeneratedMigration.toString", generated.migrations.first { it.access }.toString())
    @Test fun `GenerationResult Generated`() = clean("Generated.toString", generated.toString())
    @Test fun `AccessGeneration`() = clean("AccessGeneration.toString", AccessGenerator.generate((DefinitionsParser.parse(text) as DefinitionsParseResult.Parsed).document, GenerationRequest(emptySet(), "x")).toString())
    @Test fun `MigrationValidationResult Valid`() = clean("Valid.toString", MigrationValidationResult.Valid(accessFile).toString())
    @Test fun `MigrationParser parse of the file text`() = clean("parse result", MigrationParser.parse(accessFile.rawJson).toString())
    @Test fun `ActionsParseResult Parsed`() = clean("Parsed.toString", (MigrationParser.parseActions(MigrationParser.actionsToJson(accessFile.up))).toString().also { assertIs<ActionsParseResult.Parsed>(MigrationParser.parseActions(MigrationParser.actionsToJson(accessFile.up))) })
    @Test fun `MigrationEntry`() = clean("MigrationEntry.toString", MigrationEntry(accessFile, MigrationStatus.Pending).toString())
    @Test fun `MigrationStatus Modified`() = clean("status", MigrationEntry(accessFile, MigrationStatus.Applied(accessFile.checksum)).toString())
    @Test fun `MigrationsScreenState`() = clean("MigrationsScreenState.toString", MigrationsScreenState(entries = listOf(MigrationEntry(accessFile, MigrationStatus.Pending)), selectedVersion = accessFile.version, selectedFile = accessFile).toString())
    @Test fun `MigrationDryRun and ActionDryRun`() {
        val dry = MigrationDryRun(accessFile.version, accessFile.up.map { ActionDryRun(it, allowed = true) }, canApply = true)
        clean("MigrationDryRun.toString", dry.toString())
    }
    @Test fun `MigrationApplyResult ActionFailed`() = clean("ActionFailed.toString", MigrationApplyResult.ActionFailed(accessFile.version, accessFile.up.first { it.actionName == "declareUser" }, 2, 3, "failed").toString())
    @Test fun `the review and its state after a generation`() {
        val review = ConversionReviewsRef.core(text)
        review.generate(GenerationRequest(emptySet(), "legacy.json"))
        clean("ConversionReview.toString", review.toString())
    }
}
