/**
 * M8-05: the two apply scenarios of 16_migrate_from_3x.feature. The migration is really generated by `ConversionReview` (a classic queue
 * accepted with the ordering tick), saved with the existing file repository exactly as the later review screen will, and applied by the M5-08
 * view model with the in-memory executor. The state is that of [TopologyMigrationsSteps] (Cucumber has no DI here).
 */
class M805GeneratedApplySteps {
    private val s: TopologyMigrationsSteps get() = checkNotNull(TopologyMigrationsSteps.current) { "no scenario state" }

    private var appliedActions = 0
    private var queuesBefore = emptySet<String>()

    /** Generates the topology migration of a classic queue [name] converted to quorum and saves it into the migrations folder of the scenario. */
    private fun generateAndSave(name: String) = runBlocking {
        val document = DefinitionsDocuments.document(queues = listOf(DefinitionsDocuments.classicQueue(name)))
        val (review, report) = ConversionReviews.start(document)
        assertEquals(emptyList<Any>(), ConversionReviews.acceptEveryDefault(review, report), "the premise: the queue can be accepted")
        val result = review.generate(dev.caerbannog.core.migrate3x.GenerationRequest(emptySet(), "legacy-eu"))
        val generated = result as? GenerationResult.Generated ?: fail("the migration was not generated: $result")
        val file = generated.migrations.singleOrNull() ?: fail("expected one generated migration but got ${generated.migrations.map { it.vhost }}")
        val saved = s.fileRepository.importFile(file.file.rawJson)
        assertTrue(saved is MigrationValidationResult.Valid, "the migrations folder refused the generated file: $saved")
        s.getVm().loadMigrations()
    }

    private fun queueNames(): Set<String> = s.fakeTopologyCatalog.let { catalog -> s.executor.executedActions.map { it.description }.toSet() }

    @Given("a generated migration that declares the quorum queue {string}")
    fun generatedOneQueue(name: String) = generateAndSave(name)

    @Given("a generated migration and the user has no configure permission on the 4.x connection")
    fun generatedWithoutPermission() {
        generateAndSave("orders")
        s.configurePermission = false
        s.getVm().setConnectionContext(s.profileName, s.vhost, false, s.controlLevel)
    }

    @Given("it was applied on {string}")
    fun appliedOn(profile: String) = runBlocking {
        s.profileName = profile
        s.getVm().setConnectionContext(profile, s.vhost, s.configurePermission, s.controlLevel)
        val result = s.getVm().applyPending()
        assertTrue(result is MigrationApplyResult.Success && result.appliedVersions.size == 1, "the first apply gave $result")
        appliedActions = s.executor.executedActions.size
        assertTrue(appliedActions > 0, "the first apply declared nothing")
        queuesBefore = queueNames()
        s.topologyUnchangedCheck = {
            assertEquals(appliedActions, s.executor.executedActions.size, "the second apply sent actions to the broker: ${s.executor.executedActions.drop(appliedActions).map { it.description }}")
            assertEquals(queuesBefore, queueNames(), "the broker topology changed")
        }
    }

    @When("I apply it again on {string}")
    fun applyAgain(profile: String) = runBlocking {
        assertEquals(profile, s.profileName)
        s.lastApplyResult = s.getVm().applyPending()
        assertFalse(s.lastApplyResult is MigrationApplyResult.ActionFailed, "the second apply failed: ${s.lastApplyResult}")
    }

    @Then("I am told that the user cannot change topology")
    fun toldCannotChange() {
        val banner = s.getVm().state.value.bannerMessage
        assertNotNull(banner, "no banner is shown")
        assertTrue(banner!!.contains("cannot change topology"), "banner: $banner")
    }
}
